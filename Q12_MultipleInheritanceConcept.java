/* Java does not support extending two classes, e.g. class C extends A, B. This avoids ambiguity when parent classes define the same method. */
public class Q12_MultipleInheritanceConcept {
    public static void main(String[] args) {
        System.out.println("Java classes can extend only one class.");
        System.out.println("Multiple inheritance of classes is not supported.");
    }
}
